import { sql } from "drizzle-orm";
import {
  check,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
  varchar,
} from "drizzle-orm/pg-core";

import { formStatusEnum, formVisibilityEnum } from "./form-enums";
import type { FormSettings } from "./form-types";
import { formTemplatesTable } from "./form-templates";
import { themesTable } from "./themes";
import { usersTable } from "./user";

export const formsTable = pgTable(
  "forms",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    createdBy: text("created_by")
      .notNull()
      .references(() => usersTable.id, { onDelete: "cascade" }),
    title: varchar("title", { length: 200 }).notNull(),
    description: text("description"),
    // Generated by the API using crypto.randomBytes(12).toString("base64url").
    // The API must retry if the unique constraint detects a collision.
    shareId: varchar("share_id", { length: 16 }).notNull(),
    status: formStatusEnum("status").notNull().default("draft"),
    visibility: formVisibilityEnum("visibility").notNull().default("unlisted"),
    maxSubmissions: integer("max_submissions"),
    themeId: uuid("theme_id").references(() => themesTable.id, {
      onDelete: "set null",
    }),
    settings: jsonb("settings").$type<FormSettings>().notNull().default({}),
    sourceTemplateId: uuid("source_template_id").references(
      () => formTemplatesTable.id,
      { onDelete: "set null" },
    ),
    publishedAt: timestamp("published_at", { withTimezone: true }),
    closedAt: timestamp("closed_at", { withTimezone: true }),
    expiresAt: timestamp("expires_at", { withTimezone: true }),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    unique("forms_share_id_unique").on(table.shareId),
    index("forms_created_by_updated_at_idx").on(
      table.createdBy,
      table.updatedAt,
    ),
    index("forms_status_visibility_published_at_idx").on(
      table.status,
      table.visibility,
      table.publishedAt,
    ),
    index("forms_theme_id_idx").on(table.themeId),
    index("forms_source_template_id_idx").on(table.sourceTemplateId),
    index("forms_deleted_at_idx").on(table.deletedAt),
    check(
      "forms_max_submissions_positive_check",
      sql`${table.maxSubmissions} IS NULL OR ${table.maxSubmissions} > 0`,
    ),
  ],
);
